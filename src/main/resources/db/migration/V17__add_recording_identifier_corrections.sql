CREATE TABLE recording_identifier_correction (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    correction_key VARCHAR(64) NOT NULL,
    batch_id BIGINT UNSIGNED NOT NULL,
    revision INT NOT NULL,
    issue_id BIGINT UNSIGNED NOT NULL,
    field_type VARCHAR(32) NOT NULL,
    original_value VARCHAR(1000) NOT NULL,
    suggested_value VARCHAR(1000) NULL,
    model_value VARCHAR(512) NULL,
    source_text VARCHAR(1000) NULL,
    evidence_segment_ids_json TEXT NOT NULL,
    candidates_json TEXT NOT NULL,
    rule_score DECIMAL(6,5) NULL,
    score_margin DECIMAL(6,5) NULL,
    reason VARCHAR(1000) NULL,
    status VARCHAR(40) NOT NULL,
    confirmed_at DATETIME(6) NULL,
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    PRIMARY KEY (id),
    UNIQUE KEY uk_recording_correction_key (correction_key),
    UNIQUE KEY uk_recording_correction_issue (issue_id),
    KEY idx_recording_correction_batch_revision (batch_id, revision, status),
    CONSTRAINT fk_recording_correction_batch FOREIGN KEY (batch_id) REFERENCES recording_batch(id) ON DELETE CASCADE,
    CONSTRAINT fk_recording_correction_issue FOREIGN KEY (issue_id) REFERENCES recording_extracted_issue(id) ON DELETE CASCADE
);
